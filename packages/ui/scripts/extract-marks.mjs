// Writes OUT from the Iconify marks named in MARKS, so each surface paints offline and nothing is fetched at runtime.
// Run after `npm i`; only the chosen marks are written, never the whole set.
//   id      'name' is @iconify-json/logos (multicolor); 'set:name' is fetched once from api.iconify.design
//   mono    a brand that is one ink colour by design: every fill becomes currentColor
//   ink     a multicolor brand with black parts (TikTok): only the black becomes currentColor, hues stay as drawn
import { createRequire } from 'node:module'
import { mkdirSync, writeFileSync } from 'node:fs'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const OUT = resolve(dirname(fileURLToPath(import.meta.url)), '../src/brand-marks.generated.ts')
const MARKS = {
  youtube: 'youtube-icon',
  tiktok: { id: 'tiktok-icon', ink: true },
  instagram: 'skill-icons:instagram',
  vimeo: 'vimeo-icon',
  reddit: 'reddit-icon',
  facebook: 'facebook',
  pinterest: 'pinterest',
  gmail: 'google-gmail',
  discord: 'discord-icon',
  github: { id: 'github-icon', mono: true },
  windows: 'microsoft-windows-icon',
}

const logos = createRequire(import.meta.url)('@iconify-json/logos/icons.json')
const BLACKS = /^(#0{3}|#0{6}|#010101|#161614|#1d1d1b|#26251e|black)$/i

async function load(id) {
  if (!id.includes(':')) {
    const i = logos.icons[id]
    if (!i) throw new Error(`logos:${id} not found`)
    return { body: i.body, w: i.width ?? logos.width ?? 16, h: i.height ?? logos.height ?? 16 }
  }
  const [set, name] = id.split(':')
  const j = await (await fetch(`https://api.iconify.design/${set}.json?icons=${name}`)).json()
  const i = j.icons?.[name]
  if (!i) throw new Error(`${id} not found`)
  return { body: i.body, w: i.width ?? j.width ?? 16, h: i.height ?? j.height ?? 16 }
}

// Gradient and clip ids repeat across marks (a, b, SVGID_1); prefix them so two marks on one page cannot collide.
function scope(key, body) {
  const ids = [...body.matchAll(/\bid="([^"]+)"/g)].map((m) => m[1])
  for (const id of ids) {
    body = body.replaceAll(`id="${id}"`, `id="${key}-${id}"`).replaceAll(`url(#${id})`, `url(#${key}-${id})`).replaceAll(`href="#${id}"`, `href="#${key}-${id}"`)
  }
  return body
}

const out = {}
for (const [key, spec] of Object.entries(MARKS)) {
  const { id, mono, ink } = typeof spec === 'string' ? { id: spec } : spec
  const m = await load(id)
  let body = m.body
  if (mono) body = `<g fill="currentColor">${body.replace(/(fill|stroke)="(?!none|currentColor)[^"]*"/g, '$1="currentColor"')}</g>`
  else if (ink) body = `<g fill="currentColor">${body.replace(/fill="([^"]*)"/g, (s, c) => (BLACKS.test(c) ? 'fill="currentColor"' : s))}</g>`
  out[key] = { viewBox: `0 0 ${m.w} ${m.h}`, body: scope(key, body) }
}

mkdirSync(dirname(OUT), { recursive: true })
writeFileSync(OUT, `// Generated by extract-marks.mjs from Iconify (logos set and the sets named there); edit the script, not this file.\nexport interface Mark {\n  viewBox: string\n  body: string\n}\n\nexport const MARKS = ${JSON.stringify(out, null, 2)} satisfies Record<string, Mark>\n`)
console.log(`wrote ${Object.keys(out).length} marks, ${(JSON.stringify(out).length / 1024).toFixed(1)} KB`)
